#!/usr/bin/env python3
"""Compare results/l_beam and results/biclamped_beam with Meng et al. (2021).

    python scripts/compare_with_paper.py          (run the two examples first)

Writes results/paper_comparison.png and results/paper_comparison.md containing
  * the paper's reported numbers (Tables 1 and 2) next to ours,
  * pixel agreement / IoU of our layout with the digitized paper figure,
  * the paper's own layout re-analysed with our FE model (same equations), which
    shows that both models give the same physics for the same layout.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import matplotlib

matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.colors import ListedColormap  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from thermotopo import build, load_file  # noqa: E402

CASES = [
    dict(name='l_beam', title='L-shaped beam (paper Fig. 4)', problem='examples/l_beam.yaml',
         mask='paper_reference/fig4A_l_beam.npy',
         paper=dict(Vf=0.53, vM=568.0, T1=325.0, T2=325.0, Tmax=325.0, ratio=3.42)),
    dict(name='biclamped_beam', title='Biclamped beam (paper Fig. 12)', problem='examples/biclamped_beam.yaml',
         mask='paper_reference/fig12A_biclamped.npy',
         paper=dict(Vf=0.49, vM=513.8, T1=325.0, T2=325.0, Tmax=325.0, ratio=0.29)),
]


def main():
    rows = []
    fig, axs = plt.subplots(len(CASES), 3, figsize=(15, 4.6 * len(CASES)), layout='constrained', squeeze=False)
    for k, c in enumerate(CASES):
        res = ROOT / 'results' / c['name']
        if not (res / 'result.npz').exists():
            raise SystemExit(f'missing {res}/result.npz - run:  python run.py {c["problem"]}')
        d = np.load(res / 'result.npz')
        s = json.loads((res / 'summary.json').read_text())
        mask = np.load(ROOT / c['mask'])
        ei, ej, nx, ny = d['elem_i'], d['elem_j'], int(d['nx']), int(d['ny'])
        ref = mask[ej, ei] > 0.5
        ours = d['rho'] > 0.5
        agree = float(np.mean(ref == ours))
        iou = float(np.sum(ref & ours) / np.sum(ref | ours))
        # paper layout analysed with our FE model and the same settings
        prob, _, _ = build(load_file(ROOT / c['problem']))
        x = np.where(ref, 1.0, prob.opt.x_min)
        st = prob.analyze(prob.rho_from_x(x), sensitivities=False)
        vm = prob.stress(st)
        paper_in_ours = dict(C=st['C'], V=st['volume'], vM=vm.max() * 1e-6, T=st['T_measured'].tolist(),
                             ratio=prob.load_ratio(st)[0])
        rows.append((c, s, agree, iou, paper_in_ours))

        def grid(v):
            a = np.full((ny, nx), np.nan)
            a[ej, ei] = v
            return np.ma.masked_invalid(a)
        ext = [d['x0'], d['x0'] + nx * d['h'], d['y0'], d['y0'] + ny * d['h']]
        axs[k, 0].imshow(grid(ref.astype(float)), origin='lower', cmap='gray_r', vmin=0, vmax=1, extent=ext,
                         interpolation='nearest')
        axs[k, 0].set_title(f"{c['title']}: paper layout (digitized)")
        axs[k, 1].imshow(grid(d['rho']), origin='lower', cmap='gray_r', vmin=0, vmax=1, extent=ext, interpolation='nearest')
        axs[k, 1].set_title(f"this code: C = {s['compliance_Nm']:.4f} N m, max vM = {s['max_von_mises_MPa']:.0f} MPa")
        diff = np.where(ref & ours, 1, np.where(ours & ~ref, 2, np.where(ref & ~ours, 3, 0))).astype(float)
        cmap = ListedColormap(['white', '#444444', '#d62728', '#1f77b4'])
        axs[k, 2].imshow(grid(diff), origin='lower', cmap=cmap, vmin=-0.5, vmax=3.5, extent=ext, interpolation='nearest')
        axs[k, 2].set_title(f'overlay: agreement {agree:.1%}, IoU {iou:.2f}\n'
                            'gray = both solid, red = only ours, blue = only paper', fontsize=10)
        for a in axs[k]:
            a.set_xlabel('x (mm)')
            a.set_ylabel('y (mm)')
    fig.savefig(ROOT / 'results' / 'paper_comparison.png', dpi=140)
    plt.close(fig)

    lines = ['# Comparison with Meng et al. (2021)\n',
             'Generated by `scripts/compare_with_paper.py`. "Paper layout in our model" = the digitized paper',
             'density figure (black = solid) analysed with this code and the same settings.\n']
    for c, s, agree, iou, pio in rows:
        p = c['paper']
        T = list(s['constrained_temperatures_K'].values())
        lines += [f"## {c['title']}\n",
                  '| quantity | paper (Table) | this code | paper layout in our model |',
                  '|---|---:|---:|---:|',
                  f"| volume fraction | {p['Vf']:.3f} | {s['volume_fraction']:.3f} | {pio['V']:.3f} |",
                  f"| max von Mises, Eq. 15 (MPa) | {p['vM']:.1f} | {s['max_von_mises_MPa']:.1f} | {pio['vM']:.1f} |",
                  f"| T(H1) (K) | {p['T1']:.1f} | {T[0]:.2f} | {pio['T'][0]:.2f} |",
                  f"| T(H2) (K) | {p['T2']:.1f} | {T[1]:.2f} | {pio['T'][1]:.2f} |",
                  f"| max temperature (K) | {p['Tmax']:.1f} | {s['T_max_domain_K']:.2f} | - |",
                  f"| ‖F_th‖/‖F_m‖ | {p['ratio']:.2f} | {s['Fth_over_Fm']:.3f} | {pio['ratio']:.3f} |",
                  f"| compliance C (N m) | not reported | {s['compliance_Nm']:.4f} | {pio['C']:.4f} |",
                  f"| MMA iterations | not reported | {s['iterations']} ({s['status']}) | - |",
                  f"| pixel agreement with paper figure | 100 % | {agree:.1%} (IoU {iou:.2f}) | 100 % |", '']
    (ROOT / 'results' / 'paper_comparison.md').write_text('\n'.join(lines), encoding='utf-8')
    print('\n'.join(lines))
    print('wrote results/paper_comparison.png and results/paper_comparison.md')


if __name__ == '__main__':
    main()
